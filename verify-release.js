const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const version = require('./package.json').version;
const npm = process.env.npm_execpath;
if (!npm) throw new Error('Use npm run verify:release.');
const root = __dirname;
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'zuno-release-'));
const archive = path.join(root, 'dist', 'zuno-runtime-' + version + '.tgz');
const prefix = path.join(directory, 'install');
execFileSync(process.execPath, [npm, 'install', '--prefix', prefix, '--ignore-scripts', '--no-audit', '--no-fund', archive], { stdio: 'inherit' });
const installed = path.join(prefix, 'node_modules', 'zuno-runtime');
const manifest = JSON.parse(fs.readFileSync(path.join(installed, 'package.json'), 'utf8'));
assert.equal(manifest.version, version);
assert.equal(manifest.dependencies, undefined);
assert.equal(fs.lstatSync(installed).isSymbolicLink(), false);
const cli = path.join(installed, 'cli.js');
const run = (cwd, ...args) => execFileSync(process.execPath, [cli, ...args], { cwd, encoding: 'utf8' }).trim();
assert.equal(run(directory, '--version'), 'Zuno ' + version);
assert.ok(fs.existsSync(path.join(prefix, 'node_modules', '.bin', process.platform === 'win32' ? 'zuno.cmd' : 'zuno')));
assert.match(run(directory, 'init', 'app with spaces'), /Created/);
const project = path.join(directory, 'app with spaces');
assert.equal(run(project, 'run'), 'Welcome, Zuno');
assert.equal(run(project, 'check'), 'Syntax OK');
assert.match(run(project, 'test'), /1 passed, 0 failed/);
assert.match(run(project, 'format'), /files formatted/);
assert.match(run(project, 'format', '--check'), /0 files need formatting/);
assert.equal(run(path.join(project, 'src'), 'run'), 'Welcome, Zuno');
execFileSync('tar', ['-xzf', path.join(root, 'dist', 'zuno-starter-' + version + '.tgz'), '-C', directory]);
assert.equal(run(path.join(directory, 'starter'), 'run'), 'Welcome, Zuno');
assert.equal(run(path.join(directory, 'examples', 'modules'), 'run', 'main.zuno'), '65');
assert.equal(run(path.join(directory, 'examples', 'text-analysis'), 'run'), '5');
assert.match(run(path.join(directory, 'examples', 'text-analysis'), 'test'), /1 passed, 0 failed/);
assert.match(run(path.join(directory, 'examples', 'collections'), 'run'), /Inventory value: 340/);
assert.match(run(path.join(directory, 'examples', 'collections'), 'test'), /1 passed, 0 failed/);
const tasks = JSON.parse(fs.readFileSync(path.join(directory, 'starter', '.vscode', 'tasks.json'), 'utf8'));
assert.equal(tasks.tasks[0].command, 'zuno');
assert.ok(!JSON.stringify(tasks).includes(root));
for (const line of fs.readFileSync(path.join(root, 'dist', 'SHA256SUMS.txt'), 'utf8').trim().split('\n')) {
  const [hash, filename] = line.split('  ');
  assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(root, 'dist', filename))).digest('hex'), hash);
}
console.log('Fresh runtime install, project discovery, starter, imports, portable tasks, and checksums passed.');
console.log('Verification files: ' + directory);
execFileSync(process.execPath, [path.join(root, 'lsp-smoke.js'), path.join(root, 'editor-extension', 'dist', 'server.js')], { stdio: 'inherit' });
