const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const version = require('./package.json').version;
const extension = require('./editor-extension/package.json');
if (extension.version !== version) throw new Error('Runtime and extension versions must match.');
const npm = process.env.npm_execpath;
if (!npm) throw new Error('Use npm run package:release.');
const root = __dirname;
const destination = path.join(root, 'dist');
const npmRun = args => execFileSync(process.execPath, [npm, ...args], { cwd: root, stdio: 'inherit' });
require('./package-runtime');
npmRun(['pack', path.join(destination, 'zuno'), '--pack-destination', destination]);
npmRun(['run', 'package:extension']);
fs.copyFileSync(path.join(destination, 'zuno-tools.vsix'), path.join(destination, 'zuno-tools-' + version + '.vsix'));
const starter = fs.mkdtempSync(path.join(destination, 'starter-bundle-'));
const project = path.join(starter, 'starter');
execFileSync(process.execPath, [path.join(root, 'cli.js'), 'init', project]);
fs.cpSync(path.join(root, 'examples'), path.join(starter, 'examples'), { recursive: true });
fs.copyFileSync(path.join(root, 'INSTALL.md'), path.join(starter, 'INSTALL.md'));
execFileSync('tar', ['-czf', path.join(destination, 'zuno-starter-' + version + '.tgz'), '-C', starter, 'starter', 'examples', 'INSTALL.md']);
fs.copyFileSync(path.join(root, 'INSTALL.md'), path.join(destination, 'INSTALL.md'));
const assets = ['zuno-runtime-' + version + '.tgz', 'zuno-tools-' + version + '.vsix', 'zuno-starter-' + version + '.tgz', 'INSTALL.md'];
for (const [versioned, stable] of [[assets[0], 'zuno-runtime.tgz'], [assets[1], 'zuno-tools.vsix'], [assets[2], 'zuno-starter.tgz']]) {
  fs.copyFileSync(path.join(destination, versioned), path.join(destination, stable));
  assets.push(stable);
}
const checksums = assets.map(name => crypto.createHash('sha256').update(fs.readFileSync(path.join(destination, name))).digest('hex') + '  ' + name);
fs.writeFileSync(path.join(destination, 'SHA256SUMS.txt'), checksums.join('\n') + '\n');
console.log('Release ' + version + ' ready in dist/.');
